test('a referrer is made as a person and its page shows a person card and no People section', async ({ page, request }) => {
  const name = unique('Rui Referrer')
  await page.goto('/pipeline')
  await page.getByRole('button', { name: 'New' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel(/^Name/).fill(name)
  await dialog.getByRole('radio', { name: 'Referrer' }).click()
  await expect(dialog.getByLabel('Website')).toHaveCount(0)
  await dialog.getByLabel('Email').fill('rui.ref@example.com')
  await dialog.getByLabel('Phone').fill('+351 900 111 222')
  await dialog.getByLabel('Works at').fill('Costa Kilns')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('dialog', { name })).toBeVisible()
  const slug = new URL(page.url()).searchParams.get('org')!
  await page.goto(`/o/${slug}`)
  const card = page.locator('#person')
  await expect(card.getByRole('link', { name: 'rui.ref@example.com' })).toBeVisible()
  await expect(card.getByText('Costa Kilns')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'People' })).toHaveCount(0)
  const saved = await (await request.get(`/api/orgs/by-slug/${slug}`)).json()
  expect(saved.person).toMatchObject({ email: 'rui.ref@example.com', phone: '+351 900 111 222' })
  // An edit sends only what changed: the phone is cleared, the email stays.
  await page.getByRole('button', { name: 'Edit' }).click()
  await page.getByRole('dialog').getByLabel('Phone').fill('')
  await page.getByRole('dialog').getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  const after = await (await request.get(`/api/orgs/by-slug/${slug}`)).json()
  expect(after.person).toMatchObject({ email: 'rui.ref@example.com', phone: null })
})
